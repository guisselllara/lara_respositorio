#Declara dos numeros y muestra en pantalla si el primero es mayor, menor o igual al segundo.

# Declarar dos números
num1 = 8
num2 = 5

# Mostrar si el primero es mayor, menor o igual al segundo
if num1 > num2:
    print("El primer número es mayor que el segundo.")
elif num1 < num2:
    print("El primer número es menor que el segundo.")
else:
    print("Los números son iguales.")